/**
 * In-memory MongoDB harness for the server test suite.
 *
 * Spins up a real mongod (mongodb-memory-server) rather than stubbing Mongoose,
 * so schema validation, defaults, casting and indexes are exercised exactly as
 * they run in production. Never point this at a live URI: the helpers below
 * delete every document in the database between tests.
 *
 * One server per test file. `node --test` runs each file in its own process, so
 * the module-level singleton here is per-file by construction — files stay
 * isolated from each other and can run in parallel without sharing a database.
 *
 * Usage:
 *   import { before, after, beforeEach } from 'node:test';
 *   import * as db from '../helpers/db.js';
 *   before(async () => { await db.connect(); });
 *   beforeEach(async () => { await db.clear(); });
 *   after(async () => { await db.disconnect(); });
 *
 * ─── Tiered debug logging ────────────────────────────────────────────────────
 * TEST_DB_LOG_LEVEL = off | light | normal | verbose (default light)
 * Starting mongod shells out to a downloaded native binary, so when it fails it
 * usually fails on a machine nobody is watching (CI) and not on a laptop.
 *   off     — nothing
 *   light   — one line per server start, naming where the binary and the URI
 *             came from, plus every failure. Cheap; on by default.
 *   normal  — light, plus connect/clear/disconnect lifecycle and dbPath.
 *   verbose — normal, plus the collections each clear() dropped.
 */

import mongoose from 'mongoose';
import { MongoMemoryServer } from 'mongodb-memory-server';

const LEVELS = { off: 0, light: 1, normal: 2, verbose: 3 };

function log(level, msg) {
  // Resolved per call, not at module load, so it can't depend on import order.
  const active = LEVELS[process.env.TEST_DB_LOG_LEVEL] ?? LEVELS.light;
  if (active >= LEVELS[level]) console.log(`[tests/db:${level}] ${msg}`);
}

/** The single mongod for this test file, or null before connect()/after disconnect(). */
let mongod = null;

/**
 * Starts mongod (once) and points the default Mongoose connection at it.
 * Returns the URI, which is generated by mongodb-memory-server on a free port —
 * it is never read from the environment, so a stray MONGO_URI cannot redirect
 * a test run at a real database.
 */
export async function connect() {
  if (mongod) {
    log('normal', `connect() reused the running server (source: this module's singleton)`);
    return mongod.getUri();
  }

  try {
    mongod = await MongoMemoryServer.create();
  } catch (err) {
    log('light', `mongod failed to start (source: MongoMemoryServer.create): ${err.message}`);
    log('light', 'if this is a binary download failure, see MONGOMS_DOWNLOAD_DIR / MONGOMS_VERSION');
    throw err;
  }

  const uri = mongod.getUri();
  const info = mongod.instanceInfo ?? {};
  const binary = info.instance?.mongodProcess?.spawnfile ?? 'unknown (mongod already running?)';
  log('light', `mongod started (source: binary ${binary}, port ${info.port ?? 'auto'}); uri from MongoMemoryServer.getUri(), never from the environment`);
  log('normal', `dbPath ${info.instance?.instanceOpts?.dbPath ?? 'unknown'}; storage engine ${info.instance?.instanceOpts?.storageEngine ?? 'default'}`);

  await mongoose.connect(uri);
  log('normal', `mongoose connected (source: connect(), readyState ${mongoose.connection.readyState})`);
  return uri;
}

/**
 * Drops every collection, leaving a clean database for the next test.
 *
 * Indexes are rebuilt afterwards because dropping a collection takes its
 * indexes with it, and Mongoose only builds them once per model at init — so
 * without this a later test of a unique constraint (User.email) would pass
 * against a collection that no longer has the index enforcing it.
 */
export async function clear() {
  if (!mongod) throw new Error('clear() called before connect()');

  const collections = await mongoose.connection.db.collections();
  for (const collection of collections) {
    await collection.drop().catch((err) => {
      // 26 = NamespaceNotFound: already gone, which is the state we wanted.
      if (err.code !== 26) throw err;
    });
    log('verbose', `dropped collection ${collection.collectionName}`);
  }

  if (collections.length) {
    await mongoose.connection.syncIndexes();
    log('normal', `clear() dropped ${collections.length} collection(s) and resynced indexes (source: registered models)`);
  }
}

/** Stops Mongoose and mongod. Safe to call when connect() never ran. */
export async function disconnect() {
  await mongoose.disconnect();
  if (mongod) {
    await mongod.stop();
    log('normal', 'mongod stopped (source: disconnect())');
    mongod = null;
  }
}
